#!/usr/bin/env python3
"""Regenerate the packaged Public Suffix List snapshot.

Downloads https://publicsuffix.org/list/public_suffix_list.dat (or reads a local
copy given with ``--input``) and writes ``fasthttpc/public_suffix_list.dat.gz``:

* the MPL-2.0 notice, ``VERSION``/``COMMIT`` lines and the ICANN/PRIVATE section
  markers are kept, all other comments are dropped;
* both sections are kept (browsers use both);
* IDN labels are converted to A-labels (punycode) with the same function the
  runtime uses for host names (``fasthttpc._psl.to_ascii``);
* the output is gzip-compressed with a fixed timestamp, so an unchanged list
  gives an identical file.

The list format is checked (wildcards only as the leftmost label, no empty
labels, both sections present); a list that fails these checks is not written.
The runtime never downloads anything.

Usage (from the repository root)::

    python scripts/update_psl.py                 # download and regenerate
    python scripts/update_psl.py --input FILE    # use an already downloaded list
"""
from __future__ import annotations

import argparse
import gzip
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from fasthttpc._psl import DATA_FILE, parse, to_ascii  # noqa: E402

PSL_URL = "https://publicsuffix.org/list/public_suffix_list.dat"
OUTPUT = ROOT / "fasthttpc" / DATA_FILE
BEGIN_ICANN = "// ===BEGIN ICANN DOMAINS==="
BEGIN_PRIVATE = "// ===BEGIN PRIVATE DOMAINS==="
MIN_RULES = 5000     # the list has ~10k rules; far fewer means a truncated download
# MPL-2.0 Exhibit A notice at the top of the upstream file; kept in the snapshot.
MPL_NOTICE = [
    "// This Source Code Form is subject to the terms of the Mozilla Public",
    "// License, v. 2.0. If a copy of the MPL was not distributed with this",
    "// file, You can obtain one at https://mozilla.org/MPL/2.0/.",
]


def download(url: str = PSL_URL) -> str:
    req = urllib.request.Request(url, headers={"User-Agent": "fasthttpc-update-psl"})
    with urllib.request.urlopen(req, timeout=60) as resp:   # verifies TLS (default context)
        return resp.read().decode("utf-8")


def _check_rule(rule: str) -> None:
    body = rule[1:] if rule.startswith("!") else rule
    labels = body.split(".")
    if "" in labels:
        raise ValueError(f"empty label in rule {rule!r}")
    if any("*" in label for label in labels[1:]) or (labels[0] != "*" and "*" in labels[0]):
        # fasthttpc._psl (like Firefox and Chromium) supports "*." only as the
        # leftmost label; refuse to ship a list it would misread.
        raise ValueError(f"unsupported wildcard in rule {rule!r}")
    if rule.startswith("!") and "*" in body:
        raise ValueError(f"wildcard in exception rule {rule!r}")
    for label in labels:
        if not label.isascii():
            raise ValueError(f"label {label!r} in rule {rule!r} could not be converted to an A-label")


def build(raw: str) -> str:
    """Return the packaged (uncompressed) form of the raw list ``raw``."""
    if [line.strip() for line in raw.splitlines()[:3]] != MPL_NOTICE:
        raise ValueError("MPL-2.0 license notice not found at the top of the list")
    out: list[str] = []
    version = commit = None
    sections: list[str] = []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("//"):
            if line.startswith("// VERSION:"):
                version = line
            elif line.startswith("// COMMIT:"):
                commit = line
            elif line.startswith("// ===") and line.endswith("==="):
                out.append(line)
                if line in (BEGIN_ICANN, BEGIN_PRIVATE):
                    sections.append(line)
            continue
        rule = line.split(None, 1)[0]
        if rule.startswith("!"):
            rule = "!" + to_ascii(rule[1:])
        elif rule.startswith("*."):
            rule = "*." + to_ascii(rule[2:])
        else:
            rule = to_ascii(rule)
        _check_rule(rule)
        out.append(rule)
    if sections != [BEGIN_ICANN, BEGIN_PRIVATE]:
        raise ValueError(f"expected ICANN and PRIVATE sections, found {sections}")
    if version is None or commit is None:
        raise ValueError("VERSION/COMMIT lines not found")
    return "\n".join(MPL_NOTICE + [
        "//",
        f"// Snapshot of {PSL_URL}",
        "// generated by scripts/update_psl.py: comments dropped, IDN labels",
        "// converted to A-labels (punycode). Upstream source of this version:",
        f"// https://github.com/publicsuffix/list/blob/{commit.split(':', 1)[1].strip()}/public_suffix_list.dat",
        version,
        commit,
        "",
    ] + out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--input", type=Path, help="local public_suffix_list.dat instead of downloading")
    ap.add_argument("--output", type=Path, default=OUTPUT, help=f"default: {OUTPUT.relative_to(ROOT)}")
    args = ap.parse_args(argv)

    raw = args.input.read_text(encoding="utf-8") if args.input else download()
    text = build(raw)
    rules = parse(text)
    count = len(rules.normal) + len(rules.wildcard) + len(rules.exception)
    if count < MIN_RULES:
        raise SystemExit(f"only {count} rules, the list looks truncated; nothing written")
    data = gzip.compress(text.encode("utf-8"), compresslevel=9, mtime=0)
    args.output.write_bytes(data)

    meta = [line[3:] for line in text.splitlines() if line.startswith(("// VERSION:", "// COMMIT:"))]
    print(f"{args.output}: {len(data)} bytes, {len(rules.normal)} normal / "
          f"{len(rules.wildcard)} wildcard / {len(rules.exception)} exception rules")
    print("; ".join(meta))
    return 0


if __name__ == "__main__":
    sys.exit(main())
